/** The fields every measured row carries, whatever its model. */
interface ExitCapacityAnalogRowBase {
  readonly slug: ExitCapacityAnalogVenue
  /** history.json venue id. */
  readonly venue: string
  readonly venueName: string
  readonly asset: 'stable' | 'eth'
  readonly level: ExitCapacityAnalogLevel
  /** Nearest-rank percentile behind the level; null for 'worst'. */
  readonly percentile: number | null
  /** 1-based, worst first, of `n` events. */
  readonly rank: number
  readonly n: number
  /** First and last event onset at the venue (ISO hour): the span `n` covers. */
  readonly from: string
  readonly to: string
  /** Engine multiple of the deployed amount, lowest over the 8 h window (held basis). */
  readonly mult: number
  /** Engine freeze from the first breach, hours: the lock if `locked`, else 0. */
  readonly freezeHours: number
  /** `mult` is ≤ 1%. */
  readonly locked: boolean
  /** The ≤ 1% stretch (in the row's units) a recall inside the 8 h window runs into, hours. */
  readonly lockH: number
  readonly lockCensored: boolean
  /** Hours from onset until the row's quantity is ≥ 5% again; null = still under at the data's end. */
  readonly recover5H: number | null
  readonly recoverLowerBoundH: number | null
  /** The 72 h horizon runs past the data's end. */
  readonly horizonCensored: boolean
  /** Lowest venue free cash over the 8 h window, USD (held basis); null = unknown. */
  readonly cashUsd8h: number | null
  /** e.g. 'Kelp Apr-2026', 'ETH -13.3% 2026-06-05'. */
  readonly event: string
  readonly eventLabel: string
  /** The window the event is counted at, and its trigger. */
  readonly windowId: string
  readonly trigger: 'named' | 'eth-drop' | 'util'
  readonly onset: string
  /** Every stress window merged into the event. */
  readonly windows: readonly string[]
  /** One line for the picker. Copy-safe: never "0%", never "free". */
  readonly provenance: string
}

/** The pro-rata floor: mult = f, the withdrawable fraction (cash / supply). */
export interface ExitCapacityFloorRow extends ExitCapacityAnalogRowBase {
  readonly id: ExitCapacityFloorId
  readonly model: 'pro-rata'
  readonly bookUsd: null
  /** f at the onset reading. */
  readonly fOnset: number
  /** The same window's literal single-reading minimum over 8 h (the 'reading' basis). */
  readonly fSingleReading: number
  /** Lowest f over 72 h, held basis. */
  readonly minF72h: number
}

/** Cash-vs-book: mult = m(B) = min(1, held cash / B). */
export interface ExitCapacityBookRow extends ExitCapacityAnalogRowBase {
  readonly id: ExitCapacityBookPresetId
  readonly model: 'cash-vs-book'
  readonly book: ExitCapacityBookId
  /** Membrane's whole book at the venue, USD. */
  readonly bookUsd: number
  /** m at the onset reading. */
  readonly mOnset: number
  /** The same window's literal single-reading minimum m over 8 h (the 'reading' basis). */
  readonly mSingleReading: number
  /** Lowest m over 72 h, held basis. */
  readonly m72h: number
  /** The same window's pro-rata f over the 8 h (held): the floor's view of the same hour. */
  readonly fWindow: number
  /**
   * m < fWindow (unrounded): the book is larger than the venue's whole supply in the window,
   * so the observed history is not an analog for it (header, 'pro-rata'). The only rows that pay less than the
   * floor on the same event; their label and provenance say so.
   */
  readonly bookExceedsVenue: boolean
}

export type ExitCapacityAnalogRow = ExitCapacityFloorRow | ExitCapacityBookRow

