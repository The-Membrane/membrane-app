/**
 * exitCapacityAnalogs — the MEASURED venue exit-capacity analogs that stressGrid's
 * EXIT_CAPACITY_PRESETS resolve to. DATA ONLY and import-free: stressGrid imports it, and the
 * module that measures it (venueStressAnalogs.ts) imports measuredCapacity.ts, which imports
 * stressGrid — so the measurement cannot be a runtime import of the engine.
 *
 * Owner instruction 2026-10-06: "the venue-capacity assumptions should directly analogize
 * existing protocols (assuming typical Aave capacity during stress over the last 3 years)".
 * Each row is ONE real stress event at ONE real venue, 2023-10 → 2026-10, picked by
 * venueStressAnalogs.ts (its header defines every field): per venue the median ('typical'),
 * 10th-percentile ('bad') and worst ('worst') event over the first 8 h after the onset (the
 * Membrane delay window), on the 'held' basis (a one-reading dip the hourly keeper retries
 * past does not count).
 *
 * TWO MODELS (owner ruling 2026-10-07):
 *
 *  'cash-vs-book' — THE HEADLINE. m(B) = min(1, cash / B): the venue's free cash in USD that
 *    the held basis credits (f_held × supply — the idle cash actually observed in that hour)
 *    against Membrane's WHOLE book at that venue, B ∈ EXIT_CAPACITY_BOOKS ($10M / $50M /
 *    $250M). Every Membrane position at the venue gets the same m of its own deployment.
 *    Events are ranked per venue AND per book on m (rows `<venue>-<book>-<level>`).
 *    ASSUMPTIONS, stated wherever these rows are shown:
 *      (i)   the whole book recalls at once, at the onset (conservative: in practice only the
 *            positions that breach recall, and only down to their borrow LTV);
 *      (ii)  the observed cash is first come within the hour, and it is already NET of every
 *            other depositor who withdrew in that hour (it is what was left). Not for the
 *            Steakhouse vault: its cash is its pro-rata share of each Morpho market's idle
 *            cash, so its levels are conservative on (ii) (said in each of its rows);
 *      (iii) Membrane's recall does not itself trigger a run on the venue;
 *      (iv)  the engine's stock never refills across the horizon (the venue recovering after
 *            the window is not credited).
 *
 *  'pro-rata' — THE FLOOR (rows `<venue>-floor-<level>`). Every depositor exits at once, so a
 *    recall gets the venue's withdrawable FRACTION f = cash / supply of its deposit, whatever
 *    its size. This is not what depositors could withdraw (the cash was there for the first
 *    in line); it is the case where the whole supply races for it at the same moment. On the
 *    SAME event it never pays more than cash vs book for a book the venue could hold
 *    (B ≤ supply ⇒ cash / B ≥ cash / supply). A cash-vs-book row whose book is larger than the
 *    venue's whole supply in the window (m < the same window's f) has no analog in the observed
 *    history — if Membrane's deposit added to the supply, the venue would have been a
 *    different venue — and carries `bookExceedsVenue` (label and provenance say so); it is kept, not dropped (one row per venue × book × level, owner ruling 2026-10-07).
 *
 * MAPPING ONTO THE ENGINE (stressGrid.ts "MODELLED, NOT MASTER": the venue is one stock,
 * drawn down and never refilled; a freeze makes it unavailable from the FIRST breach):
 *   mult        = m(B) (cash-vs-book) or f (floor), lowest over the 8 h window on the held
 *                 basis, to 0.01%.
 *   freezeHours = the measured lock for a LOCKED event (mult ≤ 1%), else 0. `lockH` is the
 *                 ≤ 1% stretch the 8 h window runs into — one that starts by onset + 8 h,
 *                 measured from max(its start, onset) — in the row's own units (cash ≤ 1% of
 *                 the book, or f ≤ 1%), so the engine, which starts it at the first breach,
 *                 is early by at most 8 h: conservative, and it only removes the ≤ 1% stock
 *                 for those hours. A ≤ 1% stretch that starts after the window is not placed
 *                 at the breach, nor is an unlocked event's one-reading dip the held basis
 *                 clears. The venue's RECOVERY after a lock (`recover5H`) is not modelled: the
 *                 stock never refills.
 *
 * The rows between the generated markers are written by
 *   ./node_modules/.bin/tsx scripts/position-sim/venue-stress-analogs.ts --emit-presets
 * from public/data/venue-stress/{history,summary}.json (`exitCapacityAnalogRows`,
 * `exitCapacityBookRows`); tests/unit/venueStressAnalogs.test.ts recomputes them from the
 * data and fails on any drift.
 */

