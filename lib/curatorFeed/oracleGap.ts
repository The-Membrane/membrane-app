/**
 * Oracle-vs-market gap (Q25 T2 indicator I3), measured live. Pure: the collector reads the
 * chain and DefiLlama, the API route reads the store, this file decides.
 *
 *   gap = oracle / market − 1        oracle  = the market's Morpho oracle price() at the head
 *                                              block, in loan token per whole collateral
 *                                              token, × DefiLlama's USD price of the loan token
 *                                    market  = DefiLlama's USD price of the collateral token
 *   condition  gap ≥ constants.gap   one-sided: the oracle prices the collateral ABOVE the
 *                                    market, so positions can be under-collateralised
 *   fired      the condition holds on `persistence` consecutive OBSERVED points
 *
 * Every rule mirrors a T2 decision (membrane-datasets validation/t2/results.json `decisions`):
 *   D3  "24 consecutive observed hourly grid points with the condition true and no unobserved
 *       gap between them; the indicator fires from the 24th point on (not back-dated to the
 *       run start) and stays fired while the condition holds. Daily data: I3 fires at the
 *       2nd consecutive daily point." → `firedSince` is the 24th point, never the run start.
 *   D2  an observation stands until the next one, capped at 1.5× the native cadence; beyond
 *       the cap the time is unobserved. The hourly live series has run-time jitter, so two
 *       observed points are consecutive when ≤ 1.5 h apart (daily rows: ≤ 1.5 d). Points
 *       are deduplicated per UTC hour (the newest wins), so 24 points span 24 distinct hours.
 *   D7  a market price counts only when its own sample is less than 6 h old; else the hour
 *       is unobserved.
 *   D9  a reverting price() has no answer: the hour is unobserved, never a 0.
 * Not in T2 (its prices were frozen pulls): a DefiLlama price whose `confidence` is below
 * MIN_PRICE_CONFIDENCE is not a measurement either; the point is unobserved and its raw
 * values are kept in the store for audit (`rawGap`).
 * An unobserved point (gap null) breaks a run, as a missing hour does.
 *
 * The constants (2 %, 24 h, 2 daily points) are read from the generated record
 * (i3Record.generated.json, built from results.json), never written here.
 */

