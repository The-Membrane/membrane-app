/**
 * RATE-SPIKE FIXTURE for the stress engine's rate dimension (lib/position-sim/rateSpike.ts,
 * tests/unit/rateSpike.test.ts). It runs the REAL `rateSpikeAxis()` (lib/netApy/ratePath.ts,
 * PR #92) on the REAL irm_params the net-APY lane recorded at block 26,120,000
 * (tests/unit/fixtures/net-apy-irm.json) and writes the axes, with each venue's raw IRM
 * params beside them so a test can check the paths against the curve laws by hand.
 *
 * WHY A FIXTURE, NOT AN IMPORT. lib/netApy lives on evm-migration; the engine branch
 * (feat/risk-frontier-stress-grid) does not carry it yet. The adapter takes the axis
 * structurally, so the engine stays one-way and this file pins the real numbers.
 *
 * RUN on a checkout that has lib/netApy (evm-migration >= a9a0b5b3):
 *   tsx scripts/position-sim/build-rate-spike-fixture.mjs --root <that checkout> \
 *       --out tests/unit/fixtures/rate-spike-axis.json
 * Deterministic: no RPC, no clock. Same inputs, same bytes.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { pathToFileURL } from 'node:url'

const arg = (name, fallback) => {
  const i = process.argv.indexOf(`--${name}`)
  return i > 0 ? process.argv[i + 1] : fallback
}
const root = path.resolve(arg('root', process.cwd()))
const out = path.resolve(arg('out', 'tests/unit/fixtures/rate-spike-axis.json'))

const load = (rel) => import(pathToFileURL(path.join(root, rel)).href)
const { rateSpikeAxis, DAY_S } = await load('lib/netApy/ratePath.ts')
const { kinkUtilization } = await load('lib/netApy/irm/index.ts')
const { bigintReplacer, bigintReviver } = await load('lib/netApy/fixedPoint.ts')

const SOURCE = 'tests/unit/fixtures/net-apy-irm.json'
const recorded = JSON.parse(readFileSync(path.join(root, SOURCE), 'utf8'), bigintReviver)

/** One venue per IRM family: a static kinked curve, Morpho's adaptive curve, Euler's kink. */
const VENUES = ['aave-v3-usdc', 'morpho-blue-cbbtc-usdc-86', 'euler-v2-eusdc-2']
/** 30 days, a point every 6 h. */
const HORIZON_S = 30 * DAY_S
const STEPS = 120

/** 10 significant digits: far below any rate effect, and it keeps the file small. */
const sig = (x) => Number(x.toPrecision(10))

const axes = VENUES.map((key) => {
  const s = recorded.snapshots.find((x) => x.venueKey === key)
  if (!s) throw new Error(`${SOURCE} has no ${key}`)
  const axis = rateSpikeAxis(s, { horizonSeconds: HORIZON_S, steps: STEPS })
  return {
    venueKey: axis.venueKey,
    anchor: axis.anchor,
    label: axis.label,
    claim: axis.claim,
    horizonSeconds: axis.horizonSeconds,
    assumption: axis.assumption,
    levels: axis.levels.map((l) => ({
      name: l.name,
      utilization: sig(l.utilization),
      borrowAprNow: sig(l.borrowAprNow),
      borrowAprAtHorizon: sig(l.borrowAprAtHorizon),
      borrowAprMax: sig(l.borrowAprMax),
      supplyAprNow: sig(l.supplyAprNow),
      // The path as parallel columns (utilization is held: it equals the level's).
      t: l.path.map((p) => p.t),
      borrowApr: l.path.map((p) => sig(p.borrowApr)),
      supplyApr: l.path.map((p) => sig(p.supplyApr)),
    })),
    irm: s.irm,
    kinkUtilizationWad: kinkUtilization(s),
  }
})

const fixture = {
  _comment:
    'Generated by scripts/position-sim/build-rate-spike-fixture.mjs: the real rateSpikeAxis() (lib/netApy/ratePath.ts) on the irm_params recorded at the pinned block in ' +
    `${SOURCE}. Projections with utilization held fixed, not forecasts. Do not edit by hand.`,
  source: { file: SOURCE, anchor: recorded.anchor, horizonSeconds: HORIZON_S, steps: STEPS },
  axes,
}
// One line per number column.
const text = JSON.stringify(fixture, bigintReplacer, 1).replace(
  /\[\s+([-\d.e+,\s]+?)\s+\]/g,
  (_m, xs) => `[${xs.split(/,\s*/).join(',')}]`,
)
writeFileSync(out, `${text}\n`)
console.log(`wrote ${path.relative(process.cwd(), out)}: ${axes.length} axes`)
