#!/usr/bin/env bash
# disk-cleanup.sh: reclaim disk space from dev build output, tool caches and
# stale git worktrees. Dry run by default: nothing changes without --apply.
#
# Usage:
#   scripts/disk-cleanup.sh                    report only
#   scripts/disk-cleanup.sh --apply            clean, asking before each step
#   scripts/disk-cleanup.sh --apply --yes      clean without prompts
#   scripts/disk-cleanup.sh --apply --park     also park worktrees with unsaved work
#
# Options:
#   --root DIR    Folder to scan for projects (repeatable). Default: whichever of
#                 ~/code ~/dev ~/src ~/projects ~/repos ~/github ~/Developer
#                 ~/workspace ~/conductor ~/Documents/GitHub exist.
#   --older DAYS  Skip projects and worktrees with any file edited in the last
#                 DAYS days (default 14; 0 = include everything).
#   --only LIST   Comma-separated subset of: artifacts,caches,worktrees,report
#   --apply       Actually delete. Without it the script only reports.
#   --yes         Don't prompt. Worktrees with unsaved work are still skipped
#                 unless --park is also given.
#   --park        For worktrees with uncommitted changes: commit them locally as
#                 a WIP commit (nothing is pushed), back up gitignored files such
#                 as .env, then remove the folder. The branch keeps the work.
#                 Restore commands go to ~/.disk-cleanup/worktrees.log.
#
# Never touched: git history and branches, Docker volumes, chain/node data
# dirs, Downloads, hidden dirs such as ~/.vscode or ~/.nvm, and ~/Library
# outside the cache folders listed in section 2.

set -o pipefail

APPLY=0; YES=0; PARK=0; OLDER=14
ONLY="artifacts,caches,worktrees,report"
ROOTS=()
STATE_DIR="$HOME/.disk-cleanup"
BACKUP_LIMIT_KB=$((512 * 1024))

usage() { sed -n '2,/^$/p' "$0" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }

while [ $# -gt 0 ]; do
  case "$1" in
    --apply) APPLY=1 ;;
    --yes|-y) YES=1 ;;
    --park) PARK=1 ;;
    --older) OLDER="${2:?--older needs a number of days}"; shift ;;
    --root) ROOTS+=("${2:?--root needs a directory}"); shift ;;
    --only) ONLY="${2:?--only needs a list}"; shift ;;
    -h|--help) usage 0 ;;
    *) echo "Unknown option: $1" >&2; usage 1 ;;
  esac
  shift
done
case "$OLDER" in ''|*[!0-9]*) echo "--older must be a whole number of days" >&2; exit 1 ;; esac

# ---------------------------------------------------------------- helpers ---

if [ -t 1 ]; then B=$'\033[1m'; D=$'\033[2m'; R=$'\033[0m'; else B=; D=; R=; fi
header() { printf '\n%s== %s ==%s\n' "$B" "$1" "$R"; }
note() { printf '%s%s%s\n' "$D" "$*" "$R"; }
wants() { case ",$ONLY," in *",$1,"*) return 0 ;; esac; return 1; }
pretty() { case "$1" in "$HOME"/*) echo "~${1#"$HOME"}" ;; *) echo "$1" ;; esac; }

# KB -> 1.2G
human() {
  awk -v k="${1:-0}" 'BEGIN { split("K M G T", u, " "); i = 1
    while (k >= 1024 && i < 4) { k /= 1024; i++ }
    fmt = (i == 1) ? "%d%s" : "%.1f%s"; printf fmt, k, u[i] }'
}
size_kb() { du -sk "$@" 2>/dev/null | awk '{ s += $1 } END { print s + 0 }'; }
free_kb() { df -kP "$HOME" | awk 'NR == 2 { print $4 }'; }

confirm() {
  [ "$YES" -eq 1 ] && return 0
  local ans
  printf '%s [y/N] ' "$1" > /dev/tty 2>/dev/null || return 1
  read -r ans < /dev/tty || return 1
  case "$ans" in y|Y|yes|YES) return 0 ;; esac
  return 1
}

# Build output that is always safe to delete (regenerated by install/build).
ART_NAMES=(node_modules .next .turbo .parcel-cache .svelte-kit .nuxt target
           dist build out coverage test-results playwright-report)
ART_FIND=()
for n in "${ART_NAMES[@]}"; do ART_FIND+=(-o -name "$n"); done
ART_FIND=("${ART_FIND[@]:1}")

# Hidden dirs are skipped (~/.nvm, ~/.vscode hold global installs that look
# like projects) except where Claude Code and friends keep worktrees.
HIDDEN_FIND=(-name '.*')
for n in .claude .worktrees .next .turbo .parcel-cache .svelte-kit .nuxt; do
  HIDDEN_FIND+=(! -name "$n")
done

# Folders never walked: hidden dirs, ~/Library, and .claude/ apart from its worktrees.
SKIP_FIND=(\( "${HIDDEN_FIND[@]}" \) -o -name Library -o \( -path '*/.claude/*' ! -path '*/.claude/worktrees*' \))

ACTIVE_PRUNE=(-name .git -o -name .claude -o -name .worktrees -o "${ART_FIND[@]}")

# True if any non-build file under $1 changed in the last $OLDER days.
recently_active() {
  [ "$OLDER" -eq 0 ] && return 1
  [ -n "$(find "$1" -mindepth 1 -type d \( "${ACTIVE_PRUNE[@]}" \) -prune \
          -o -type f -mtime -"$OLDER" -print 2>/dev/null | head -n 1)" ]
}

find_artifacts() {
  find "$1" -mindepth 1 -type d \( "${SKIP_FIND[@]}" \) -prune \
    -o -type d \( "${ART_FIND[@]}" \) -prune -print0 2>/dev/null
}

find_repos() {
  find "$1" -mindepth 1 -type d -name .git -prune -print0 \
    -o -type d \( "${SKIP_FIND[@]}" -o "${ART_FIND[@]}" \) -prune 2>/dev/null
}

# ------------------------------------------------------------------ roots ---

if [ ${#ROOTS[@]} -eq 0 ]; then
  for d in code dev src projects repos github Developer workspace conductor Documents/GitHub; do
    [ -d "$HOME/$d" ] && ROOTS+=("$HOME/$d")
  done
fi
NORM=()
for r in "${ROOTS[@]}"; do
  if [ -d "$r" ]; then NORM+=("$(cd "$r" && pwd -P)"); else echo "Skipping $r (not a directory)" >&2; fi
done
ROOTS=("${NORM[@]}")

inside_roots() {
  local r
  for r in "${ROOTS[@]}"; do case "$1/" in "$r"/*) return 0 ;; esac; done
  return 1
}

# -------------------------------------------------------------- discovery ---

WT_REPO=(); WT_PATH=(); WT_BRANCH=(); WT_LOCKED=(); WT_MISSING=()
EXTRA_SCAN=()

collect_worktrees() {
  local repo="$1" line path="" branch="" locked=0 missing=0 first=1
  while IFS= read -r line; do
    case "$line" in
      "worktree "*) path="${line#worktree }" ;;
      "branch "*) branch="${line#branch refs/heads/}" ;;
      locked*) locked=1 ;;
      prunable*) missing=1 ;;
      "")
        if [ -n "$path" ]; then
          if [ $first -eq 1 ]; then
            first=0   # the main checkout is never touched
          else
            [ -d "$path" ] || missing=1
            WT_REPO+=("$repo"); WT_PATH+=("$path"); WT_BRANCH+=("$branch")
            WT_LOCKED+=("$locked"); WT_MISSING+=("$missing")
            if [ $missing -eq 0 ] && ! inside_roots "$path"; then EXTRA_SCAN+=("$path"); fi
          fi
        fi
        path=""; branch=""; locked=0; missing=0 ;;
    esac
  done < <(git -C "$repo" worktree list --porcelain 2>/dev/null; echo)
}

discover() {
  local r g
  for r in "${ROOTS[@]}"; do
    while IFS= read -r -d '' g; do collect_worktrees "${g%/.git}"; done < <(find_repos "$r")
  done
}

# ------------------------------------------------- 1. build output ---

TOTAL_KB=0

section_artifacts() {
  header "1. Build output (node_modules, .next, target, dist, ...)"
  if [ ${#ROOTS[@]} -eq 0 ]; then note "No project folders found. Pass --root DIR."; return; fi

  local list; list=$(mktemp)
  local dir name parent kb active=0 r
  for r in "${ROOTS[@]}" "${EXTRA_SCAN[@]}"; do
    [ -n "$r" ] || continue
    while IFS= read -r -d '' dir; do
      name=$(basename "$dir"); parent=$(dirname "$dir")
      case "$name" in
        target) [ -f "$parent/Cargo.toml" ] || continue ;;
        node_modules|.next|.turbo|.parcel-cache|.svelte-kit|.nuxt)
          [ -f "$parent/package.json" ] || continue ;;
        *) # generic names: only when next to package.json AND gitignored
          [ -f "$parent/package.json" ] && git -C "$parent" check-ignore -q "$name" 2>/dev/null || continue ;;
      esac
      if recently_active "$parent"; then active=$((active + 1)); continue; fi
      kb=$(size_kb "$dir")
      printf '%s\t%s\n' "$kb" "$dir" >> "$list"
    done < <(find_artifacts "$r")
  done

  local count total
  sort -rn -o "$list" "$list"
  count=$(awk 'END { print NR }' "$list")
  total=$(awk -F'\t' '{ s += $1 } END { print s + 0 }' "$list")
  if [ "$count" -eq 0 ]; then
    note "Nothing to clean."
  else
    awk -F'\t' 'NR <= 25 { print $1 "\t" $2 }' "$list" | while IFS=$'\t' read -r kb dir; do
      printf '  %8s  %s\n' "$(human "$kb")" "$(pretty "$dir")"
    done
    [ "$count" -gt 25 ] && note "  ... and $((count - 25)) more"
    printf '  %s%d folders, ~%s%s\n' "$B" "$count" "$(human "$total")" "$R"
    note "  pnpm node_modules share files with the pnpm store, so deleting them frees less"
    note "  than shown until the store is pruned in section 2."
  fi
  [ $active -gt 0 ] && note "  Kept $active folder(s) in projects edited in the last $OLDER days."
  TOTAL_KB=$((TOTAL_KB + total))

  if [ $APPLY -eq 1 ] && [ "$count" -gt 0 ] && confirm "Delete these $count folders?"; then
    while IFS=$'\t' read -r kb dir; do
      case "$dir" in /*) ;; *) continue ;; esac
      case " ${ART_NAMES[*]} " in *" $(basename "$dir") "*) rm -rf "$dir" && echo "  deleted $(pretty "$dir")" ;; esac
    done < "$list"
  fi
  rm -f "$list"
}

# ------------------------------------------------------ 2. caches ---

CACHE_LABEL=(); CACHE_CMD=(); CACHE_KB=(); CACHE_NOTE=()

# add_cache LABEL COMMAND NOTE PATH...  (paths are only used for sizing)
add_cache() {
  local label="$1" cmd="$2" note="$3" p kb existing=()
  shift 3
  for p in "$@"; do [ -n "$p" ] && [ -e "$p" ] && existing+=("$p"); done
  [ ${#existing[@]} -eq 0 ] && return
  kb=$(size_kb "${existing[@]}")
  [ "$kb" -lt 10240 ] && return   # ignore anything under 10 MB
  CACHE_LABEL+=("$label"); CACHE_CMD+=("$cmd"); CACHE_KB+=("$kb"); CACHE_NOTE+=("$note")
}

# add_cache_dir LABEL NOTE PATH...  (deletes the paths themselves)
add_cache_dir() {
  local label="$1" note="$2" p cmd="rm -rf"
  shift 2
  for p in "$@"; do [ -e "$p" ] && cmd="$cmd $(printf '%q' "$p")"; done
  [ "$cmd" = "rm -rf" ] && return
  add_cache "$label" "$cmd" "$note" "$@"
}

section_caches() {
  header "2. Tool caches"
  local cargo="${CARGO_HOME:-$HOME/.cargo}"
  command -v pnpm >/dev/null && add_cache "pnpm store (unused packages)" "pnpm store prune" \
    "only frees packages no project uses; run after section 1" "$(pnpm store path 2>/dev/null)"
  command -v npm >/dev/null && add_cache "npm cache" "npm cache clean --force" "" "$HOME/.npm/_cacache"
  add_cache_dir "Yarn cache" "" "$HOME/Library/Caches/Yarn" "$HOME/.cache/yarn" "$HOME/.yarn/berry/cache"
  add_cache_dir "Bun cache" "" "$HOME/.bun/install/cache"
  command -v brew >/dev/null && add_cache "Homebrew downloads" "brew cleanup -s --prune=all" "" "$(brew --cache 2>/dev/null)"
  add_cache_dir "Cargo downloaded crates" "downloaded again on next build" \
    "$cargo/registry/cache" "$cargo/registry/src" "$cargo/git/checkouts"
  command -v pip3 >/dev/null && add_cache "pip cache" "pip3 cache purge" "" "$(pip3 cache dir 2>/dev/null)"
  command -v go >/dev/null && add_cache "Go build cache" "go clean -cache" "" "$(go env GOCACHE 2>/dev/null)"
  add_cache_dir "Playwright browsers" "run 'npx playwright install' again where needed" \
    "$HOME/Library/Caches/ms-playwright" "$HOME/.cache/ms-playwright"
  add_cache_dir "Foundry RPC cache" "" "$HOME/.foundry/cache"
  add_cache_dir "Xcode DerivedData" "" "$HOME/Library/Developer/Xcode/DerivedData"
  add_cache_dir "Xcode iOS DeviceSupport" "recreated when a device is plugged in" \
    "$HOME/Library/Developer/Xcode/iOS DeviceSupport"
  add_cache_dir "Simulator caches" "" "$HOME/Library/Developer/CoreSimulator/Caches"

  local i
  if [ ${#CACHE_LABEL[@]} -eq 0 ]; then note "No caches over 10 MB."; fi
  for i in "${!CACHE_LABEL[@]}"; do
    printf '  %8s  %s' "$(human "${CACHE_KB[$i]}")" "${CACHE_LABEL[$i]}"
    [ -n "${CACHE_NOTE[$i]}" ] && printf '  %s(%s)%s' "$D" "${CACHE_NOTE[$i]}" "$R"
    printf '\n'
    TOTAL_KB=$((TOTAL_KB + CACHE_KB[i]))
  done

  local docker_ok=0
  if command -v docker >/dev/null && docker info >/dev/null 2>&1; then
    docker_ok=1
    echo
    echo "  Docker (reclaimable):"
    docker system df --format '{{.Type}}\t{{.Reclaimable}}' 2>/dev/null |
      while IFS=$'\t' read -r t rc; do printf '  %14s  %s\n' "$rc" "$t"; done
    note "  Only images and build cache are cleaned. Volumes (local DB data) are left alone."
  fi

  [ $APPLY -eq 1 ] || return
  for i in "${!CACHE_LABEL[@]}"; do
    if confirm "Clean ${CACHE_LABEL[$i]} (~$(human "${CACHE_KB[$i]}"))?"; then
      echo "  \$ ${CACHE_CMD[$i]}"
      eval "${CACHE_CMD[$i]}" >/dev/null || echo "  (failed, skipped)"
    fi
  done
  if [ $docker_ok -eq 1 ] && confirm "Prune Docker build cache and unused images (they'll re-pull)?"; then
    docker builder prune -af >/dev/null && docker image prune -af >/dev/null && echo "  Docker pruned"
  fi
}

# --------------------------------------------------- 3. worktrees ---

# Copy gitignored files that aren't build output (.env, local config) out of
# a worktree before removing it. `git worktree remove` deletes them silently.
backup_ignored() {
  local wt="$1" dest="$2" p files=()
  while IFS= read -r -d '' p; do
    case "$p" in '!! '*) p="${p#!! }" ;; *) continue ;; esac
    p="${p%/}"
    case "/$p/" in
      */node_modules/*|*/.next/*|*/.turbo/*|*/.parcel-cache/*|*/.svelte-kit/*|*/.nuxt/*|\
      */target/*|*/dist/*|*/build/*|*/out/*|*/coverage/*|*/test-results/*|\
      */playwright-report/*|*/.DS_Store/*) continue ;;
    esac
    case "$p" in *.tsbuildinfo|next-env.d.ts) continue ;; esac
    files+=("./$p")
  done < <(git -C "$wt" --no-optional-locks status --porcelain --ignored -z 2>/dev/null)
  [ ${#files[@]} -eq 0 ] && return 0

  local kb; kb=$(cd "$wt" && size_kb "${files[@]}")
  if [ "$kb" -gt "$BACKUP_LIMIT_KB" ]; then
    echo "  gitignored files total $(human "$kb"), too big to back up; skipping this worktree"
    return 1
  fi
  mkdir -p "$dest" && (cd "$wt" && tar cf - "${files[@]}") | (cd "$dest" && tar xf -) || return 1
  echo "  backed up ${#files[@]} gitignored file(s) to $(pretty "$dest")"
}

# Commit uncommitted work locally so the worktree can be removed. Detached
# HEADs get a branch so the commit stays reachable. Nothing is pushed.
park() {
  local wt="$1" branch="$2"
  if [ -z "$branch" ]; then
    branch="wip/parked-$(date +%Y%m%d-%H%M%S)-$(basename "$wt" | tr -c 'A-Za-z0-9._\n-' '-')"
    git -C "$wt" checkout -q -b "$branch" || return 1
  fi
  PARKED_BRANCH="$branch"; PARKED_WIP=0
  if [ -n "$(git -C "$wt" --no-optional-locks status --porcelain)" ]; then
    git -C "$wt" add -A &&
      git -C "$wt" commit -q --no-verify -m "wip: parked by disk-cleanup on $(date +%Y-%m-%d)" || return 1
    PARKED_WIP=1
  fi
}

remove_worktree() { # repo path branch wip(0|1)
  local repo="$1" wt="$2" branch="$3" wip="$4"
  local dest
  dest="$STATE_DIR/worktree-backups/$(basename "$repo")/$(basename "$wt")-$(date +%Y%m%d-%H%M%S)"
  backup_ignored "$wt" "$dest" || return 1
  git -C "$repo" worktree remove "$wt" || { echo "  git refused to remove it; left as is"; return 1; }
  echo "  removed $(pretty "$wt") (branch $branch kept)"
  mkdir -p "$STATE_DIR"
  {
    echo "# $(date '+%Y-%m-%d %H:%M') removed $wt"
    printf 'git -C %q worktree add %q %q\n' "$repo" "$wt" "$branch"
    [ "$wip" -eq 1 ] && printf 'git -C %q reset HEAD~1   # undo the WIP commit, keep the changes\n' "$wt"
    [ -d "$dest" ] && printf 'cp -R %q/. %q/\n' "$dest" "$wt"
    echo
  } >> "$STATE_DIR/worktrees.log"
}

section_worktrees() {
  header "3. Git worktrees (sizes include build output from section 1)"
  if [ ${#WT_PATH[@]} -eq 0 ]; then note "No extra worktrees found."; return; fi

  local i repo wt branch dirty orphan unpushed ct age kb size state detail
  local prune_repos=""
  for i in "${!WT_PATH[@]}"; do
    repo="${WT_REPO[$i]}"; wt="${WT_PATH[$i]}"; branch="${WT_BRANCH[$i]}"
    detail=""
    if [ "${WT_MISSING[$i]}" -eq 1 ]; then
      state="missing"; kb=0; detail="folder is gone; git still lists it"
      case "$prune_repos" in *"|$repo|"*) ;; *) prune_repos="$prune_repos|$repo|" ;; esac
    elif [ "${WT_LOCKED[$i]}" -eq 1 ]; then
      state="locked"; kb=$(size_kb "$wt"); detail="locked; left alone"
    else
      kb=$(size_kb "$wt")
      dirty=$(git -C "$wt" --no-optional-locks status --porcelain 2>/dev/null | awk 'END { print NR }')
      orphan=$(git -C "$wt" rev-list --count HEAD --not --branches --remotes 2>/dev/null || echo 0)
      unpushed=0
      [ -n "$(git -C "$wt" remote)" ] &&
        unpushed=$(git -C "$wt" rev-list --count HEAD --not --remotes 2>/dev/null || echo 0)
      ct=$(git -C "$wt" log -1 --format=%ct 2>/dev/null || echo 0)
      age=$(( ($(date +%s) - ${ct:-0}) / 86400 ))
      detail="${branch:-detached HEAD}, last commit ${age}d ago"
      [ "$unpushed" -gt 0 ] && detail="$detail, $unpushed unpushed commit(s)"
      if recently_active "$wt"; then
        state="active"; detail="$detail; edited in the last ${OLDER}d, kept"
      elif [ "$dirty" -gt 0 ] || [ "$orphan" -gt 0 ]; then
        state="unsaved"
        [ "$dirty" -gt 0 ] && detail="$detail, $dirty uncommitted file(s)"
        [ "$orphan" -gt 0 ] && detail="$detail, $orphan commit(s) on no branch"
      else
        state="clean"
      fi
    fi
    if [ "$state" = missing ]; then size="-"; else size=$(human "$kb"); fi
    printf '  %-9s %8s  %s\n' "[$state]" "$size" "$(pretty "$wt")"
    note "                      $detail"

    [ $APPLY -eq 1 ] || continue
    case "$state" in
      clean)
        confirm "Remove this worktree? (branch and commits are kept)" &&
          remove_worktree "$repo" "$wt" "${branch:-$(git -C "$wt" rev-parse HEAD)}" 0 ;;
      unsaved)
        if [ $PARK -eq 0 ]; then
          note "  has unsaved work; re-run with --park to commit it locally and remove the folder"
        elif confirm "Park (local WIP commit, nothing pushed) and remove this worktree?"; then
          if park "$wt" "$branch"; then
            remove_worktree "$repo" "$wt" "$PARKED_BRANCH" "$PARKED_WIP"
          else
            echo "  could not commit the WIP; left as is"
          fi
        fi ;;
    esac
  done

  if [ $APPLY -eq 1 ] && [ -n "$prune_repos" ] && confirm "Forget worktrees whose folders are gone (git worktree prune)?"; then
    local IFS='|'
    for repo in $prune_repos; do [ -n "$repo" ] && git -C "$repo" worktree prune && echo "  pruned $(pretty "$repo")"; done
  fi
  [ $APPLY -eq 1 ] && [ -f "$STATE_DIR/worktrees.log" ] && note "  Restore commands: $(pretty "$STATE_DIR/worktrees.log")"
}

# -------------------------------------------- 4. review by hand ---

section_report() {
  header "4. Review by hand (never deleted by this script)"
  local p kb shown=0

  # Big files in places old exports pile up
  local big; big=$(find "$HOME/Downloads" "$HOME/Desktop" "$HOME/Movies" "$HOME/Documents" \
    -type f -size +500M 2>/dev/null | head -n 200)
  if [ -n "$big" ]; then
    echo "  Files over 500 MB:"
    while IFS= read -r p; do printf '%s\t%s\n' "$(size_kb "$p")" "$p"; done <<< "$big" |
      sort -rn | head -n 15 | while IFS=$'\t' read -r kb p; do
        printf '  %8s  %s\n' "$(human "$kb")" "$(pretty "$p")"
      done
    shown=1
  fi

  # Local chain data: may hold keys, so only report
  for p in "$HOME"/.neutrond "$HOME"/.osmosisd "$HOME"/.gaia "$HOME"/.junod "$HOME"/.wasmd \
           "$HOME"/.injectived "$HOME"/.ethereum "$HOME/Library/Ethereum" "$HOME/.foundry/anvil"; do
    [ -d "$p" ] || continue
    kb=$(size_kb "$p"); [ "$kb" -lt 102400 ] && continue
    printf '  %8s  %s  %s(chain data, may contain keys)%s\n' "$(human "$kb")" "$(pretty "$p")" "$D" "$R"
    shown=1
  done

  for p in "$HOME/.Trash" "$HOME/Library/Application Support/MobileSync/Backup"; do
    [ -d "$p" ] || continue
    kb=$(size_kb "$p"); [ "$kb" -lt 102400 ] && continue
    printf '  %8s  %s\n' "$(human "$kb")" "$(pretty "$p")"
    shown=1
  done

  if command -v tmutil >/dev/null; then
    local snaps; snaps=$(tmutil listlocalsnapshots / 2>/dev/null | grep -c 'com.apple')
    if [ "${snaps:-0}" -gt 0 ]; then
      echo "  $snaps local Time Machine snapshot(s). Free them with: tmutil thinlocalsnapshots / 999999999999 4"
      shown=1
    fi
  fi
  [ $shown -eq 0 ] && note "Nothing large found."
}

# ------------------------------------------------------------------- main ---

BEFORE=$(free_kb)
if [ $APPLY -eq 1 ]; then mode="APPLY"; else mode="dry run, nothing will be deleted (add --apply to clean)"; fi
echo "${B}disk-cleanup${R}: $mode"
echo "Free space: $(human "$BEFORE")"
if [ ${#ROOTS[@]} -gt 0 ]; then
  scanned=""
  for r in "${ROOTS[@]}"; do scanned="$scanned $(pretty "$r")"; done
  echo "Scanning:$scanned"
fi
[ "$OLDER" -gt 0 ] && note "Skipping anything edited in the last $OLDER days (--older 0 to include)."

if wants artifacts || wants worktrees; then discover; fi
wants artifacts && section_artifacts
wants caches && section_caches
wants worktrees && section_worktrees
wants report && section_report

echo
if [ $APPLY -eq 1 ]; then
  AFTER=$(free_kb)
  echo "${B}Freed $(human $((AFTER - BEFORE)))${R}. Free space now: $(human "$AFTER")"
else
  echo "${B}Estimated reclaimable: ~$(human "$TOTAL_KB")${R} (plus Docker and worktrees, listed above)"
  echo "Next: scripts/disk-cleanup.sh --apply    (add --park to also clear worktrees with unsaved work)"
fi
