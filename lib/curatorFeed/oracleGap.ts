export type I3State = 'fired' | 'building' | 'below' | 'unobserved' | 'stale'
export type I3Cadence = 'hourly' | 'daily'

export interface I3Result {
  state: I3State
  /** Gap at the newest point when it is observed. */
  currentGap?: number
  /** Consecutive observed points with gap ≥ constants.gap, ending at the newest point. */
  hoursAboveConsecutive: number
  /** Points needed to fire (constants.persistenceHours, or the daily-point count). */
  persistence: number
  /** Time of the point at which the current run reached `persistence` (D3). */
  firedSince?: number
  lastObservedTs?: number
  /** Newest point, observed or not. */
  lastTs?: number
}

/** D2: two observed points are consecutive when at most this far apart. */
export const HOLD_SECONDS: Record<I3Cadence, number> = { hourly: 1.5 * 3600, daily: 1.5 * 86400 }
/** D7: a market-price sample older than this leaves the point unobserved. */
export const MARKET_HOLD_SECONDS = 6 * 3600
/** The live state is stale when the newest point is older than this. */
export const STALE_HOURS = 3
/**
 * A DefiLlama price below this confidence is not a measurement. DefiLlama's coins API
 * returns `confidence` per price, "Confidence score (0-1) indicating price reliability"
 * (@defillama/api 0.1.3, dist/index.d.cts, the current / historical price types); its API
 * docs (api-docs.defillama.com) set no cut. 0.9 is ours. On 2026-10-14 (block 26,187,700)
 * the lower confidence of each held market's two prices was 0.99 for 234 markets, 0.9 for
 * 34, 0.95 to 0.995 for 10, and 0.85 for 2 (armUSDCp, armUSDTp): the cut drops only what
 * DefiLlama rates below its usual levels. Applied when a point is read (decodeGapFile), so
 * the stored raw value can be re-read under another cut.
 */
export const MIN_PRICE_CONFIDENCE = 0.9

const lowConfidence = (c: number | null | undefined): boolean =>
  c !== null && c !== undefined && c < MIN_PRICE_CONFIDENCE

export const persistenceOf = (c: I3Constants, cadence: I3Cadence): number =>
  cadence === 'hourly' ? c.persistenceHours : c.persistenceDailyPoints

/** Hourly: one point per UTC hour, the newest wins. Sorted oldest first. */
export function dedupeHourly<T extends { ts: number }>(xs: readonly T[]): T[] {
  const bySlot = new Map<number, T>()
  for (const x of [...xs].sort((a, b) => a.ts - b.ts)) bySlot.set(Math.floor(x.ts / 3600), x)
  return [...bySlot.values()]
}

export interface I3Point {
  ts: number
  gap: number | null
  cond: boolean
  /** Consecutive observed points with the condition true, ending here. */
  run: number
  fired: boolean
}

/** The indicator at every point (the replay of T2's per-point `fired` column). */
export function i3Points(
  observations: readonly Pick<GapObservation, 'ts' | 'gap'>[],
  constants: I3Constants,
  cadence: I3Cadence = 'hourly',
): I3Point[] {
  const pts =
    cadence === 'hourly'
      ? dedupeHourly(observations)
      : [...observations].sort((a, b) => a.ts - b.ts)
  const need = persistenceOf(constants, cadence)
  const hold = HOLD_SECONDS[cadence]
  const out: I3Point[] = []
  let run = 0
  let prevTs: number | undefined
  for (const p of pts) {
    const observed = p.gap !== null && Number.isFinite(p.gap)
    const cond = observed && (p.gap as number) >= constants.gap
    if (!cond) run = 0
    else run = run > 0 && prevTs !== undefined && p.ts - prevTs <= hold ? run + 1 : 1
    // An unobserved point still ends the hold of the point before it.
    prevTs = observed ? p.ts : undefined
    out.push({ ts: p.ts, gap: observed ? (p.gap as number) : null, cond, run, fired: run >= need })
  }
  return out
}

/** State of one market at `nowTs` (unix s). See the file header. */
export function evaluateI3(
  observations: readonly Pick<GapObservation, 'ts' | 'gap'>[],
  constants: I3Constants,
  nowTs: number,
  cadence: I3Cadence = 'hourly',
): I3Result {
  const persistence = persistenceOf(constants, cadence)
  const pts = i3Points(observations, constants, cadence)
  const observed = pts.filter((p) => p.gap !== null)
  if (!observed.length)
    return { state: 'unobserved', hoursAboveConsecutive: 0, persistence, lastTs: pts.at(-1)?.ts }
  const last = pts[pts.length - 1]
  const lastObs = observed[observed.length - 1]
  const firedSince = (p: I3Point, i: number) =>
    p.fired ? pts[i - (p.run - persistence)].ts : undefined
  const base = { persistence, lastObservedTs: lastObs.ts, lastTs: last.ts }
  if (nowTs - last.ts > STALE_HOURS * 3600) {
    const i = pts.lastIndexOf(lastObs)
    return {
      ...base,
      state: 'stale',
      currentGap: lastObs.gap ?? undefined,
      hoursAboveConsecutive: lastObs.run,
      firedSince: firedSince(lastObs, i),
    }
  }
  if (last.gap === null) return { ...base, state: 'unobserved', hoursAboveConsecutive: 0 }
  return {
    ...base,
    state: last.fired ? 'fired' : last.run > 0 ? 'building' : 'below',
    currentGap: last.gap,
    hoursAboveConsecutive: last.run,
    firedSince: firedSince(last, pts.length - 1),
  }
}

// ── the rolling store (oracle-gap.json, format in ./store.ts) ──────────────────

/** Days of runs kept: 7 × the 24 h persistence, room for a week of context. */
export const KEEP_DAYS = 7

export interface GapRun {
  ts: number
  block: number
}

type Tuple =
  | [oracleUsd: number, marketUsd: number, confidence: number | null, gap: number]
  | [
      oracleUsd: number,
      marketUsd: number,
      confidence: number | null,
      gap: number,
      loanUsd: number,
      loanPegUsd: number,
    ]
type RunRows = GapRun & { rows: Map<string, Tuple> }

function toRuns(f: OracleGapFile | null): RunRows[] {
  const runs: RunRows[] = (f?.runs ?? []).map(([ts, block]) => ({ ts, block, rows: new Map() }))
  for (const [ri, mi, ...t] of f?.rows ?? []) runs[ri]?.rows.set(f!.markets[mi], t as Tuple)
  return runs
}

function fromRuns(runs: RunRows[], keepDays: number): OracleGapFile {
  const markets: string[] = []
  const idx = new Map<string, number>()
  const rows: OracleGapRow[] = []
  runs.forEach((r, ri) => {
    for (const m of [...r.rows.keys()].sort()) {
      let mi = idx.get(m)
      if (mi === undefined) {
        mi = markets.length
        markets.push(m)
        idx.set(m, mi)
      }
      rows.push([ri, mi, ...r.rows.get(m)!] as OracleGapRow)
    }
  })
  return {
    schema: ORACLE_GAP_SCHEMA,
    chainId: 1,
    marketSource: 'defillama',
    keepDays,
    runs: runs.map((r) => [r.ts, r.block]),
    markets,
    rows,
  }
}

export type AppendResult = 'appended' | 'replaced' | 'skipped-empty' | 'skipped-older'

/**
 * Add one run's observations. Observed points are stored, and low-confidence points with
 * their raw gap (for audit; they read back as unobserved); a market without a row is
 * unobserved in that run. A run that observed nothing is not recorded (so the series goes
 * stale rather than pretending to have looked). A run in the same UTC hour as the newest
 * one replaces it; a run older than the newest is ignored. Runs older than `keepDays`
 * before the newest are dropped.
 */
export function appendGapRun(
  prev: OracleGapFile | null,
  run: GapRun,
  observations: Iterable<[market: string, obs: GapObservation]>,
  keepDays = KEEP_DAYS,
): { file: OracleGapFile; result: AppendResult } {
  const rows = new Map<string, Tuple>()
  let observed = 0
  for (const [m, o] of observations) {
    // Stored: the whole gap as measured (loan token at DefiLlama) and, for a pegged loan
    // token, its price and its peg's, so the reader splits the two sides (decodeGapFile).
    const g = o.fullGap ?? o.gap ?? o.rawGap
    if (g === null || g === undefined || !Number.isFinite(g)) continue
    if (o.oracleUsd === undefined || o.marketUsd === undefined) continue
    const c = o.marketConfidence ?? null
    // An observation with a split carries oracleUsd at the peg; the row keeps it as read.
    rows.set(
      m.toLowerCase(),
      o.loanUsd !== undefined && o.loanPegUsd !== undefined
        ? [
            sig6((o.oracleUsd * o.loanUsd) / o.loanPegUsd),
            o.marketUsd,
            c,
            g,
            o.loanUsd,
            o.loanPegUsd,
          ]
        : [o.oracleUsd, o.marketUsd, c, g],
    )
    if (o.gap !== null) observed++
  }
  const runs = toRuns(prev)
  const keep = (result: AppendResult) => ({ file: fromRuns(runs, keepDays), result })
  if (!observed) return keep('skipped-empty')
  const last = runs[runs.length - 1]
  if (last && run.ts < last.ts) return keep('skipped-older')
  let result: AppendResult = 'appended'
  if (last && Math.floor(run.ts / 3600) === Math.floor(last.ts / 3600)) {
    runs.pop()
    result = 'replaced'
  }
  runs.push({ ts: run.ts, block: run.block, rows })
  const from = run.ts - keepDays * 86_400
  return {
    file: fromRuns(
      runs.filter((r) => r.ts > from),
      keepDays,
    ),
    result,
  }
}

/**
 * Per market, one observation per run from its first stored run to the newest run; a run
 * without a row for the market is an unobserved point (gap null), and so is a row whose
 * confidence is below MIN_PRICE_CONFIDENCE (its gap moves to `rawGap`).
 */
export function decodeGapFile(f: OracleGapFile): {
  runs: GapRun[]
  byMarket: Map<string, GapObservation[]>
} {
  const runs = f.runs.map(([ts, block]) => ({ ts, block }))
  const first = new Map<string, number>()
  const cells = new Map<string, Map<number, OracleGapRow>>()
  for (const row of f.rows) {
    const m = f.markets[row[1]]
    if (!cells.has(m)) cells.set(m, new Map())
    cells.get(m)!.set(row[0], row)
    first.set(m, Math.min(first.get(m) ?? row[0], row[0]))
  }
  const byMarket = new Map<string, GapObservation[]>()
  for (const [m, byRun] of cells) {
    const out: GapObservation[] = []
    for (let ri = first.get(m)!; ri < runs.length; ri++) {
      const r = byRun.get(ri)
      if (!r) {
        out.push({ ...runs[ri], gap: null })
        continue
      }
      const low = lowConfidence(r[4])
      const split = splitRow(r)
      const gap = split ? split.gap : r[5]
      out.push({
        ...runs[ri],
        oracleUsd: split ? split.oracleUsd : r[2],
        marketUsd: r[3],
        marketSource: 'defillama',
        marketConfidence: r[4] ?? undefined,
        gap: low ? null : gap,
        ...(low ? { rawGap: gap } : {}),
        ...(split
          ? {
              fullGap: r[5],
              loanUsd: split.loanUsd,
              loanPegUsd: split.loanPegUsd,
              loanGap: split.loanGap,
            }
          : {}),
      })
    }
    byMarket.set(m, out)
  }
  return { runs, byMarket }
}

/** A row with the loan token's price and its peg's: the two sides, split. */
function splitRow(r: OracleGapRow) {
  if (r.length < 8) return undefined
  const [, , oracleRead, , , full, loanUsd, loanPegUsd] = r as unknown as number[]
  if (!(loanUsd > 0) || !(loanPegUsd > 0)) return undefined
  return {
    oracleUsd: sig6((oracleRead * loanPegUsd) / loanUsd),
    gap: Math.round(((1 + full) * (loanPegUsd / loanUsd) - 1) * 1e6) / 1e6,
    loanUsd,
    loanPegUsd,
    loanGap: Math.round((loanUsd / loanPegUsd - 1) * 1e6) / 1e6,
  }
}

