/** A DefiLlama coins API price (coins.llama.fi/prices/current). */
export interface LlamaPrice {
  price: number
  /** Unix s of the sample. */
  timestamp: number
  confidence?: number
  decimals?: number
  symbol?: string
}

export type UnobservedReason =
  | 'oracle-reverts'
  | 'oracle-unread'
  | 'no-decimals'
  | 'decimals-disagree'
  | 'no-loan-price'
  | 'loan-price-old'
  | 'no-market-price'
  | 'market-price-old'
  | 'zero-price'
  | 'low-confidence'

export interface GapInputs {
  ts: number
  block: number
  /** price() at `block`, 1e36-scaled decimal string; null = reverts; undefined = not read. */
  price: string | null | undefined
  collateralDecimals?: number
  loanDecimals?: number
  collateral?: LlamaPrice
  loan?: LlamaPrice
  /** The USD value of the loan token's peg (PEGS: $1, or WETH's price). Given, the gap is
   *  split: `gap` is collateral-side (the loan token at its peg), `loanGap` loan-side. */
  loanPegUsd?: number
}

const sig6 = (x: number) => Number(x.toPrecision(6))

/**
 * One observation, or an unobserved point with its reason. The oracle side is
 * price() / 1e36 × 10^(collateral decimals − loan decimals) loan tokens per whole collateral
 * token (Morpho Blue IOracle: "price of 1 asset of collateral quoted in 1 asset of loan
 * token, scaled by 1e36"), times DefiLlama's loan-token USD price — no token is taken as
 * $1 (T2 D5 took 1 USDC = $1; the live series converts USDC too). Prices are stored at 6
 * significant digits and the gap at 6 decimals; the condition reads the stored gap.
 */
export function observeGap(i: GapInputs): { obs: GapObservation; reason?: UnobservedReason } {
  const none = (reason: UnobservedReason) => ({
    obs: { ts: i.ts, block: i.block, marketSource: 'defillama' as const, gap: null },
    reason,
  })
  if (i.price === null) return none('oracle-reverts')
  if (i.price === undefined) return none('oracle-unread')
  const cd = i.collateralDecimals ?? i.collateral?.decimals
  const ld = i.loanDecimals ?? i.loan?.decimals
  if (cd === undefined || ld === undefined) return none('no-decimals')
  // Token decimals read on chain vs DefiLlama's: a disagreement makes the scale unknown.
  if (
    (i.collateral?.decimals !== undefined && i.collateral.decimals !== cd) ||
    (i.loan?.decimals !== undefined && i.loan.decimals !== ld)
  )
    return none('decimals-disagree')
  if (!i.loan || !(i.loan.price > 0)) return none('no-loan-price')
  if (i.ts - i.loan.timestamp >= MARKET_HOLD_SECONDS) return none('loan-price-old')
  if (!i.collateral || !(i.collateral.price > 0)) return none('no-market-price')
  if (i.ts - i.collateral.timestamp >= MARKET_HOLD_SECONDS) return none('market-price-old')
  const loanPerColl = (Number(BigInt(i.price)) / 1e36) * 10 ** (cd - ld)
  if (!(loanPerColl > 0)) return none('zero-price')
  const asRead = loanPerColl * i.loan.price
  const full = Math.round((asRead / i.collateral.price - 1) * 1e6) / 1e6
  const peg = i.loanPegUsd !== undefined && i.loanPegUsd > 0 ? i.loanPegUsd : undefined
  // Split: the oracle with the loan token at its peg, against the collateral's market.
  const oracleUsd = peg !== undefined ? loanPerColl * peg : asRead
  const gap =
    peg !== undefined ? Math.round((oracleUsd / i.collateral.price - 1) * 1e6) / 1e6 : full
  const confs = [i.collateral.confidence, i.loan.confidence].filter(
    (c): c is number => typeof c === 'number',
  )
  const confidence = confs.length ? Math.min(...confs) : undefined
  const obs: GapObservation = {
    ts: i.ts,
    block: i.block,
    oracleUsd: sig6(oracleUsd),
    marketUsd: sig6(i.collateral.price),
    marketSource: 'defillama',
    marketConfidence: confidence,
    gap,
    ...(peg !== undefined
      ? {
          fullGap: full,
          loanUsd: sig6(i.loan.price),
          loanPegUsd: sig6(peg),
          loanGap: Math.round((i.loan.price / peg - 1) * 1e6) / 1e6,
        }
      : {}),
  }
  if (lowConfidence(confidence))
    return { obs: { ...obs, gap: null, rawGap: gap }, reason: 'low-confidence' }
  return { obs }
}

