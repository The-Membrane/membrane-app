const MINUS = '−'

/** Above this gap the text is ">1,000%": the oracle and DefiLlama prices beside it give
 *  the detail (a fixed oracle over a collapsed token reads in the billions of %). */
export const GAP_TEXT_CAP = 10

/** "+2.31%" / "−0.40%": a signed gap, 2 decimals; ">1,000%" above GAP_TEXT_CAP. */
export const gapText = (gap: number): string => {
  if (gap > GAP_TEXT_CAP) return `>${(GAP_TEXT_CAP * 100).toLocaleString('en-US')}%`
  const s = (Math.abs(gap) * 100).toFixed(2)
  return `${gap < 0 && s !== '0.00' ? MINUS : '+'}${s}%`
}

/** Whole % of the condition, e.g. 0.02 → "2%". */
export const thresholdText = (c: Pick<I3Constants, 'gap'>): string =>
  `${Number((c.gap * 100).toPrecision(3))}%`

/** Lead days: ≥ 10 → whole days, else one decimal. */
export const leadDaysText = (d: number): string => (d >= 10 ? String(Math.round(d)) : d.toFixed(1))

/** The finding, ink only. Undefined while there is nothing to state (stale, unmeasured). */
export function i3Headline(
  firedCount: number,
  c: Pick<I3Constants, 'gap' | 'persistenceHours'>,
): string {
  const cond = `oracle ≥ ${thresholdText(c)} above market for ${c.persistenceHours} h`
  if (firedCount === 0) return `No ${cond}`
  return `${firedCount} market${firedCount === 1 ? '' : 's'}: ${cond}`
}

const plural = (n: number, w: string) => `${n} ${w}${n === 1 ? '' : 's'}`

export interface RecordLine {
  label: string
  /** T0 day, 'YYYY-MM-DD'. */
  date: string
  value: string
}

/** The historical record as label / value rows, in the record's order. */
export function recordLines(r: I3Record): RecordLine[] {
  const c = r.constants
  const out: RecordLine[] = [
    {
      label: `warned ≥ ${c.warnDays} days ahead`,
      date: '',
      value: `${r.passLine.incidentsWarned} of ${r.incidentCount} incidents`,
    },
  ]
  const byIncident = new Map<string, I3RecordRow[]>()
  for (const x of r.incidents)
    byIncident.set(x.incident, [...(byIncident.get(x.incident) ?? []), x])
  for (const [incident, rows] of byIncident) {
    const silent = rows.filter((x) => x.leadDays === null)
    const fired = rows.filter((x) => x.leadDays !== null)
    for (const x of fired)
      out.push({
        label: `${x.asset} ${x.event}`,
        date: x.T0.slice(0, 10),
        value:
          `fired ${leadDaysText(x.leadDays as number)} days before` +
          (x.warned9d ? '' : ` (under ${c.warnDays} days)`) +
          ` · ${plural(x.calmEpisodeStarts, 'false alarm')} in ${Math.floor(x.calmDays)} calm days`,
      })
    if (silent.length > 1 && silent.length === rows.length)
      out.push({
        label: `${incident.replace(/\s\d{4}$/, '')} ${rows[0].event}`,
        date: rows[0].T0.slice(0, 10),
        value: `did not fire · ${silent.map((x) => x.asset).join(', ')}`,
      })
    else
      for (const x of silent)
        out.push({ label: `${x.asset} ${x.event}`, date: x.T0.slice(0, 10), value: 'did not fire' })
  }
  return out
}

/** One footer line of caveats, every figure from the record. */
export function recordCaveats(r: I3Record): string {
  const testId = r.test.split(/\s/)[0]
  const parts = [
    `Retrospective, n = ${r.incidentCount} incidents (${r.lane} ${testId}: ${r.verdict} overall).`,
  ]
  for (const x of r.incidents)
    if (x.calmEpisodeStarts > 0 && !x.warned9d) {
      const years = [...new Set(x.calmFireStarts.map((s) => s.slice(0, 4)))].join(', ')
      parts.push(
        `${x.asset}: ${plural(x.calmEpisodeStarts, 'false alarm')}${years ? ` in ${years}` : ''}.`,
      )
    }
  for (const x of r.incidents)
    if (x.oracleFixed)
      parts.push(`${x.asset}'s oracle was fixed at ${x.oracleFixed.value} ${x.oracleFixed.unit}.`)
  return parts.join(' ')
}

